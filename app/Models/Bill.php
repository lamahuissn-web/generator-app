<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

class Bill extends Model
{
    protected $fillable = [
        'subscriber_id', 'period', 'type', 'reading_id', 'consumption', 'kwh_price',
        'usage_amount', 'maintenance_fee', 'flat_amount', 'prev_debt', 'total', 'paid_amount',
    ];

    public function subscriber(): BelongsTo
    {
        return $this->belongsTo(Subscriber::class);
    }

    public function reading(): BelongsTo
    {
        return $this->belongsTo(Reading::class);
    }

    public function allocations(): HasMany
    {
        return $this->hasMany(PaymentAllocation::class);
    }

    /** Charges generated by this period's activity (excludes rolled-over prev_debt). */
    public function charges(): float
    {
        return (float) $this->usage_amount + (float) $this->maintenance_fee + (float) $this->flat_amount;
    }

    public function unpaidAmount(): float
    {
        return max(0, (float) $this->total - (float) $this->paid_amount);
    }

    /** paid | partial | unpaid */
    public function paymentStatus(): string
    {
        $unpaid = $this->unpaidAmount();

        return $unpaid <= 0 ? 'paid' : ((float) $this->paid_amount > 0 ? 'partial' : 'unpaid');
    }
}
